/**
 * Retrieve the high-quality image URL for a given vocabulary word or ID
 */
export function getVocabularyImage(word: string, id?: string): string {
  if (id && VOCABULARY_IMAGE_MAP[id]) {
    return VOCABULARY_IMAGE_MAP[id];
  }
  const cleanWord = word.trim().toLowerCase();
  if (VOCABULARY_IMAGE_MAP[cleanWord]) {
    return VOCABULARY_IMAGE_MAP[cleanWord];
  }

  // If word has parentheses like "listen (to music)", check base word
  const stripped = cleanWord.replace(/\(.*\)/g, '').trim();
  if (VOCABULARY_IMAGE_MAP[stripped]) {
    return VOCABULARY_IMAGE_MAP[stripped];
  }

  // Fallback high quality nature/education photo
  return 'https://images.unsplash.com/photo-1497633762265-9d179a990aa6?w=600&auto=format&fit=crop&q=80';
}
